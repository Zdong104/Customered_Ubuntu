#!/usr/bin/env python3
"""Turn payload/dconf/defaults.ini into a gschema override.

Every [schema] group is emitted twice: as [schema] and as [schema:ubuntu],
because Ubuntu's 10_ubuntu-settings.gschema.override sets ":ubuntu"
session-specific values that win in the Ubuntu session. Our file sorts after
it (90_), so for the same key our value wins in both cases.

Usage: gen-override.py defaults.ini > 90_preload.gschema.override
"""
import os
import re
import sys

# Refuse values that look personal. The owner's identity strings live outside
# this public repo; the build passes them in PRELOAD_IDENT_RE (test/leakscan.sh
# --repo also checks defaults.ini at release time).
PERSONAL = re.compile(r"/home/" + ("|" + os.environ["PRELOAD_IDENT_RE"] if os.environ.get("PRELOAD_IDENT_RE") else ""), re.I)
ALLOWED_PERSONAL_KEYS = {"enabled-extensions"}  # custom extension UUIDs, kept by decision


def main(path):
    groups, cur = [], None
    for raw in open(path, encoding="utf-8"):
        line = raw.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.fullmatch(r"\[([A-Za-z0-9.\-]+)\]", line.strip())
        if m:
            cur = (m.group(1), [])
            groups.append(cur)
            continue
        if cur is None or "=" not in line:
            sys.exit(f"bad line: {line!r}")
        key, val = line.split("=", 1)
        key = key.strip()
        if PERSONAL.search(val) and key not in ALLOWED_PERSONAL_KEYS:
            sys.exit(f"refusing personal-looking value for {cur[0]} {key}")
        cur[1].append((key, val.strip()))
    out = ["# Generated by build/gen-override.py from payload/dconf/defaults.ini", ""]
    for suffix in ("", ":ubuntu"):
        for schema, kvs in groups:
            out.append(f"[{schema}{suffix}]")
            out += [f"{k}={v}" for k, v in kvs]
            out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
